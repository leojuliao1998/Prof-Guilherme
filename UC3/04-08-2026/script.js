let numero = Number(prompt("Digite um número: "))
    if (numero >= 1){
        document.write("<h1>Este número é POSITIVO!</h1>")
    }
    else if (numero == 0){
        document.write("<h1>Este número é igual a ZERO!</h1>")
    }
    else{
        document.write("<h1>Este número é NEGATIVO!</h1>")
    }